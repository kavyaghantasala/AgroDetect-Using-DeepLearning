def get_localized_disease_name(class_name: str, lang: str = "en") -> Tuple[str, str, str, bool]:
    """
    Returns (display_name, crop, condition, is_healthy) in the requested language.
    """
    is_healthy = "healthy" in class_name.lower()
    
    # 1. Base extraction
    if "___" in class_name:
        parts = class_name.split("___", 1)
        raw_crop = parts[0].strip()
        raw_cond = parts[1].replace("_", " ").strip()
    else:
        raw_crop = "Plant"
        raw_cond = class_name.replace("_", " ").strip()

    # 2. Localized class lookup
    class_entry = CLASS_TRANSLATIONS.get(class_name, {})
    display_name = class_entry.get(lang) or class_entry.get("en")
    
    # 3. Localized crop lookup
    crop_entry = CROP_TRANSLATIONS.get(raw_crop, {})
    crop = crop_entry.get(lang) or crop_entry.get("en") or raw_crop.replace("_", " ").title()

    if not display_name:
        cond_title = raw_cond.title() if not is_healthy else "Healthy"
        display_name = f"{crop} - {cond_title}"
    
    # Extract condition
    if " - " in display_name:
        condition = display_name.split(" - ", 1)[1]
    else:
        condition = display_name

    return display_name, crop, condition, is_healthy
